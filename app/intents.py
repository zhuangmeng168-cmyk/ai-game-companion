# 意图 → 知识库章节关键词
SECTION_HINTS: dict[str, tuple[str, ...]] = {
    "lane": ("对线",),
    "teamfight": ("团战",),
    "build": ("装备", "出装", "发育"),
    "jungle": ("打野", "节奏"),
    "dragon": ("资源", "龙"),
    "pick": ("英雄", "阵容", "配队", "养成"),
    "basics": ("开局", "基础", "入门", "探索"),
    "where": ("视野", "地图", "位置"),
    "circle": ("转移", "圈"),
    "jump": ("跳伞", "落点"),
    "loot": ("搜物资", "物资"),
    "combat": ("交战", "刚枪"),
    "team": ("队友", "配合"),
    "boss": ("战斗", "元素"),
    "farm": ("圣遗物", "日常", "养成", "天赋"),
    "daily": ("日常", "探索", "养成"),
}


def classify(text: str) -> str:
    text = (text or "").lower()
    best, best_hits = "general", 0
    for intent, words in INTENT_RULES:
        hits = sum(1 for word in words if word and word.lower() in text)
        if hits > best_hits:
            best, best_hits = intent, hits
    return best


def expand(query: str) -> tuple[str, str]:
    """返回（扩展后的检索词，意图）。"""
    intent = classify(query)
    hint = " ".join(SECTION_HINTS.get(intent, ()))
    return f"{query} {hint}".strip(), intent
